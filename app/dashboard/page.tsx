import Link from "next/link";
import { formatDistanceToNow } from "date-fns";
import { PlusCircledIcon } from "@radix-ui/react-icons";
import { generateMeta } from "@/lib/utils";
import { serverFetch } from "@/lib/api.server";
import type { AdminStats, AppUser, Paginated, Plan } from "@/lib/types";
import { labelOf, humanize } from "@/lib/options";
import { GOALS } from "@/lib/profile-options";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Avatar, AvatarFallback } from "@/components/ui/avatar";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { generateAvatarFallback } from "@/lib/utils";
import { PageHeader } from "@/components/shared/page-header";
import { StatCard } from "@/components/shared/stat-card";
import { SignupsChart } from "./components/signups-chart";

export async function generateMetadata() {
  return generateMeta({
    title: "Dashboard",
    description: "BirFit overview",
    canonical: "/dashboard"
  });
}

export default async function Page() {
  const [stats, users, plans] = await Promise.all([
    serverFetch<AdminStats>("/admin/stats"),
    serverFetch<Paginated<AppUser>>("/admin/users?limit=6"),
    serverFetch<Paginated<Plan>>("/admin/plans?limit=6")
  ]);

  return (
    <div className="space-y-4">
      <PageHeader title="Dashboard" description="What is happening in BirFit right now.">
        <Button asChild>
          <Link href="/dashboard/exercises/new">
            <PlusCircledIcon /> <span className="hidden lg:inline">Add exercise</span>
          </Link>
        </Button>
      </PageHeader>

      <div className="grid gap-4 md:grid-cols-3">
        <StatCard
          label="Members"
          value={stats.users.total}
          hint={`+${stats.users.lastWeek} this week`}
          href="/dashboard/users"
        />
        <StatCard
          label="Plans generated"
          value={stats.plans.total}
          hint={`+${stats.plans.lastWeek} this week`}
          href="/dashboard/plans"
        />
        <StatCard
          label="Published exercises"
          value={stats.exercises.published}
          hint={`${stats.exercises.total - stats.exercises.published} drafts`}
          href="/dashboard/exercises"
        />
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <div className="lg:col-span-2">
          <SignupsChart data={stats.signups} />
        </div>
        <Card>
          <CardHeader>
            <CardTitle>New members</CardTitle>
            <CardDescription>Most recent sign-ups</CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            {users.items.length === 0 && (
              <p className="text-muted-foreground text-sm">No members yet.</p>
            )}
            {users.items.map((user) => (
              <Link
                key={user.id}
                href={`/dashboard/users/${user.id}`}
                className="hover:bg-muted/60 -mx-2 flex items-center gap-3 rounded-md px-2 py-1.5"
              >
                <Avatar className="size-9">
                  <AvatarFallback>{generateAvatarFallback(user.fullName)}</AvatarFallback>
                </Avatar>
                <div className="min-w-0 flex-1">
                  <div className="truncate text-sm font-medium">{user.fullName}</div>
                  <div className="text-muted-foreground truncate text-xs">
                    {labelOf(GOALS, user.goal)} · {humanize(user.trainingPlace)}
                  </div>
                </div>
                <div className="text-muted-foreground text-xs whitespace-nowrap">
                  {formatDistanceToNow(new Date(user.createdAt), { addSuffix: true })}
                </div>
              </Link>
            ))}
          </CardContent>
        </Card>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Latest plans</CardTitle>
          <CardDescription>Plans generated by Gemini for members</CardDescription>
        </CardHeader>
        <CardContent className="divide-y">
          {plans.items.length === 0 && (
            <p className="text-muted-foreground text-sm">No plans yet.</p>
          )}
          {plans.items.map((plan) => (
            <Link
              key={plan.id}
              href={`/dashboard/users/${plan.userId}`}
              className="hover:bg-muted/60 -mx-2 flex items-center gap-4 rounded-md px-2 py-3"
            >
              <div className="min-w-0 flex-1">
                <div className="truncate text-sm font-medium">
                  {plan.user?.fullName ?? "Member"}
                </div>
                <div className="text-muted-foreground line-clamp-1 text-xs">{plan.summary}</div>
              </div>
              <Badge variant="outline">{plan.workouts.length} sessions</Badge>
              <Badge variant="secondary">{plan.nutrition.dailyKcal} kcal</Badge>
              <div className="text-muted-foreground hidden text-xs whitespace-nowrap md:block">
                {formatDistanceToNow(new Date(plan.createdAt), { addSuffix: true })}
              </div>
            </Link>
          ))}
        </CardContent>
      </Card>
    </div>
  );
}
