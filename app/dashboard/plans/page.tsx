import { Suspense } from "react";
import { generateMeta } from "@/lib/utils";
import { serverFetch } from "@/lib/api.server";
import type { Paginated, Plan } from "@/lib/types";
import { PageHeader } from "@/components/shared/page-header";
import { Pagination } from "@/components/shared/pagination";
import { PlansTable } from "./components/plans-table";

export async function generateMetadata() {
  return generateMeta({
    title: "Plans",
    description: "Generated plans",
    canonical: "/dashboard/plans"
  });
}

type SearchParams = Record<string, string | string[] | undefined>;

export default async function Page({ searchParams }: { searchParams: Promise<SearchParams> }) {
  const params = await searchParams;
  const query = new URLSearchParams({ limit: "20" });
  if (typeof params.page === "string") query.set("page", params.page);
  const result = await serverFetch<Paginated<Plan>>(`/admin/plans?${query.toString()}`);

  return (
    <div className="space-y-4">
      <PageHeader title="Plans" description={`${result.total} plans generated by Gemini`} />
      <PlansTable data={result.items} />
      <Suspense>
        <Pagination page={result.page} limit={result.limit} total={result.total} />
      </Suspense>
    </div>
  );
}
